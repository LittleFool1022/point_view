import type { PointCloudData } from "./types";

export function parsePly(buffer: ArrayBuffer, id: string = crypto.randomUUID()): PointCloudData {
  const bytes = new Uint8Array(buffer);
  const probe = new TextDecoder().decode(bytes.subarray(0, Math.min(bytes.length, 32_768)));
  const marker = "end_header";
  const markerAt = probe.indexOf(marker);
  if (!probe.startsWith("ply") || markerAt < 0) throw new Error("不是有效的 PLY 文件");
  const newlineAt = probe.indexOf("\n", markerAt);
  const dataOffset = new TextEncoder().encode(probe.slice(0, newlineAt + 1)).length;
  const header = probe.slice(0, newlineAt);
  const format = /format\s+(ascii|binary_little_endian)/.exec(header)?.[1];
  if (!format) throw new Error("仅支持 ASCII 或 binary_little_endian PLY");
  const count = Number(/element\s+vertex\s+(\d+)/.exec(header)?.[1] ?? 0);
  const vertexBlock = header.split(/element\s+vertex\s+\d+/)[1]?.split(/element\s+/)[0] ?? "";
  const properties = [...vertexBlock.matchAll(/property\s+(\w+)\s+(\w+)/g)].map((m) => ({ type: m[1]!, name: m[2]! }));
  const positions = new Float32Array(count * 3);
  const colors = new Uint8Array(count * 3);
  const intensities = properties.some((p) => p.name === "intensity") ? new Float32Array(count) : undefined;
  const names = properties.map((p) => p.name);

  if (format === "ascii") {
    const values = new TextDecoder().decode(bytes.subarray(dataOffset)).trim().split(/\s+/).map(Number);
    for (let i = 0; i < count; i++) {
      const row = values.slice(i * properties.length, (i + 1) * properties.length);
      writeVertex(i, names, row, positions, colors, intensities);
    }
  } else {
    const sizes: Record<string, number> = { char: 1, uchar: 1, int8: 1, uint8: 1, short: 2, ushort: 2, int16: 2, uint16: 2, int: 4, uint: 4, int32: 4, uint32: 4, float: 4, float32: 4, double: 8, float64: 8 };
    const stride = properties.reduce((sum, p) => sum + (sizes[p.type] ?? 4), 0);
    const view = new DataView(buffer, dataOffset);
    const read = (type: string, offset: number) => {
      if (type === "char" || type === "int8") return view.getInt8(offset);
      if (type === "uchar" || type === "uint8") return view.getUint8(offset);
      if (type === "short" || type === "int16") return view.getInt16(offset, true);
      if (type === "ushort" || type === "uint16") return view.getUint16(offset, true);
      if (type === "int" || type === "int32") return view.getInt32(offset, true);
      if (type === "uint" || type === "uint32") return view.getUint32(offset, true);
      if (type === "double" || type === "float64") return view.getFloat64(offset, true);
      return view.getFloat32(offset, true);
    };
    for (let i = 0; i < count; i++) {
      let offset = i * stride;
      const values = properties.map((property) => {
        const value = read(property.type, offset);
        offset += sizes[property.type] ?? 4;
        return value;
      });
      writeVertex(i, names, values, positions, colors, intensities);
    }
  }
  return { id, frameId: "camera_init", stampNs: 0n, positions, colors, intensities, visible: new Uint8Array(count).fill(1) };
}

function writeVertex(index: number, names: string[], values: number[], positions: Float32Array, colors: Uint8Array, intensities?: Float32Array) {
  const value = (name: string, fallback = 0) => values[names.indexOf(name)] ?? fallback;
  const dst = index * 3;
  positions[dst] = value("x"); positions[dst + 1] = value("y"); positions[dst + 2] = value("z");
  colors[dst] = value("red", 69); colors[dst + 1] = value("green", 214); colors[dst + 2] = value("blue", 255);
  if (intensities) intensities[index] = value("intensity");
}

export function exportPly(cloud: PointCloudData): Uint8Array {
  const indices = Array.from(cloud.visible.keys()).filter((index) => cloud.visible[index]);
  const header = `ply\nformat binary_little_endian 1.0\ncomment generated by Point View\nelement vertex ${indices.length}\nproperty float x\nproperty float y\nproperty float z\nproperty uchar red\nproperty uchar green\nproperty uchar blue\nend_header\n`;
  const head = new TextEncoder().encode(header);
  const body = new Uint8Array(indices.length * 15);
  const view = new DataView(body.buffer);
  indices.forEach((point, row) => {
    const source = point * 3;
    const offset = row * 15;
    view.setFloat32(offset, cloud.positions[source]!, true);
    view.setFloat32(offset + 4, cloud.positions[source + 1]!, true);
    view.setFloat32(offset + 8, cloud.positions[source + 2]!, true);
    body[offset + 12] = cloud.colors[source]!;
    body[offset + 13] = cloud.colors[source + 1]!;
    body[offset + 14] = cloud.colors[source + 2]!;
  });
  const output = new Uint8Array(head.length + body.length);
  output.set(head); output.set(body, head.length);
  return output;
}

import {openStudioView} from "./studioPage";
import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
const root=process.env.PAIRED_WORKSPACE;
test("真实桌上采集：联合定位、类别修正、复核导出与工程恢复", async ({page})=>{
  test.skip(!root,"设置 PAIRED_WORKSPACE 指向实际配对工程目录");
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/");
  const open=page.waitForEvent("filechooser");await page.getByRole("button",{name:"打开工程",exact:true}).click();await(await open).setFiles(`${root}/桌上采集-联合复核.pvplan`);
  await expect(page.locator(".status-bar")).toContainText("测量工程已恢复",{timeout:30000});await openStudioView(page,"关键帧复核");
  await expect(page.getByRole("button",{name:"关键帧复核",exact:true})).toHaveAttribute("aria-current","page");
  await expect(page.locator(".work-toolbar")).toContainText("13 张原图 · 5 条候选");
  await expect(page.locator(".cloud-view")).toHaveAttribute("data-review-candidate","view-0-0");
  await expect.poll(async()=>Number(await page.locator(".cloud-view").getAttribute("data-review-points"))).toBeGreaterThan(0);
  await page.getByRole("button",{name:"图像候选 view-0-1 窗",exact:true}).click();
  await expect(page.locator(".cloud-view")).toHaveAttribute("data-review-candidate","view-0-1");
  await expect.poll(async()=>Number(await page.locator(".cloud-view").getAttribute("data-review-points"))).toBeGreaterThan(0);
  await expect(page.locator(".paired-inspector")).toContainText("723 点");
  await page.getByRole("button",{name:"保留候选",exact:true}).click();
  await page.getByLabel("复核备注",{exact:true}).fill("左窗被画面截断，仅保留可见证据");
  await page.screenshot({path:"artifacts/paired-review-real.png"});
  await page.getByRole("button",{name:"图像候选 view-0-0 门",exact:true}).click();
  await page.getByLabel("复核类别",{exact:true}).selectOption("window");
  await page.getByRole("button",{name:"已排除",exact:true}).click();
  const exported=page.waitForEvent("download");await page.getByRole("button",{name:"导出复核记录",exact:true}).click();
  const decisions=JSON.parse(await readFile((await(await exported).path())!,"utf8"));
  expect(decisions.sourceSha256).toBe("1f43b3f7f7ceba0a23bbc7bfc2e24c2c71aeb6f57899dccb321354b841eeb3b6");
  expect(decisions.constructionAccepted).toBe(false);expect(decisions.frames[0].candidates[0]).toMatchObject({decision:"reject",reviewedLabel:"window"});
  const saved=page.waitForEvent("download");await page.getByRole("button",{name:"保存工程",exact:true}).click();const project=await saved;
  const reopen=page.waitForEvent("filechooser");await page.getByRole("button",{name:"打开工程",exact:true}).click();await(await reopen).setFiles((await project.path())!);
  await expect(page.locator(".status-bar")).toContainText("测量工程已恢复",{timeout:30000});await openStudioView(page,"关键帧复核");
  await expect(page.getByLabel("复核类别",{exact:true})).toHaveValue("window");
  await expect(page.getByRole("button",{name:"已排除",exact:true})).toHaveAttribute("aria-pressed","true");
  await page.getByRole("button",{name:"图像候选 view-0-1 窗",exact:true}).click();
  await expect(page.getByLabel("复核备注",{exact:true})).toHaveValue("左窗被画面截断，仅保留可见证据");
  await page.getByLabel("关键帧选择",{exact:true}).selectOption("frame-1");
  await expect(page.locator(".paired-inspector")).toContainText("尚未识别");
  expect(errors).toEqual([]);
});

test("观察按钮与快捷键可退出编辑并恢复自动双栏", async ({ page }) => {
  await page.goto("/"); await page.getByRole("button", { name: "打开示例", exact: true }).click();
  await expect(page.locator(".status-bar")).toContainText("合成示例");
  const observe = page.getByRole("button", { name: "观察", exact: true });
  const erase = page.getByRole("button", { name: "橡皮擦", exact: true });
  const select = page.getByRole("button", { name: "选区", exact: true });
  await expect(observe).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".cloud-view")).toHaveClass(/tool-none/);
  await erase.click(); await expect(page.locator(".work-body")).toHaveClass(/focus-cloud/);
  await expect(observe).toHaveAttribute("aria-pressed", "false");
  await erase.click(); await expect(observe).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".work-body")).not.toHaveClass(/focus-cloud/);
  await select.click(); await expect(page.getByLabel("选区选项", { exact: true })).toBeVisible();
  await page.keyboard.press("v");
  await expect(observe).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".cloud-options")).toHaveCount(0);
  await expect(page.locator(".work-body")).not.toHaveClass(/focus-cloud/);
  await page.locator(".cloud-pane .pane-focus-btn").click();
  await erase.click(); await observe.click();
  await expect(page.locator(".work-body")).toHaveClass(/focus-cloud/);
  await page.locator(".cloud-pane .pane-focus-btn").click();
  await expect(page.locator(".work-body")).not.toHaveClass(/focus-cloud/);
});


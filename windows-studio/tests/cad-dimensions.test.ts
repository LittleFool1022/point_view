import {expect,it} from 'vitest';
import {writeFileSync,mkdirSync} from 'node:fs';
import {dimensionMeasurement,appendDimension,dimensionGeometry,validateDimensions,type CadDimension} from '../../src/cad/dimensions';
import {exportCadDxf} from '../../src/cad/dxf';
import {applyCadAnnotations,validateDrawingModel} from '../../src/cad/model';
import {decodeSource,generateDrawing} from '../src/pipeline/analysis';
import {demoRoom} from '../src/domain/demo';
import {decodeProject,encodeProject} from '../src/domain/project';
import {applyClips,validateClips} from '../src/domain/cleaning';
it('原生尺寸保留非整毫米定义、方向、取整；文字编辑和工程往返不破坏尺寸',async()=>{
 const bytes=demoRoom(),cloud=await decodeSource('room.pcd',bytes,'m');
 const model=generateDrawing(cloud,'room.pcd','xy',{});
 const d:CadDimension={id:'manual-precise',kind:'aligned',start:[100.25,200.125],end:[3100.65,4200.325],linePoint:[-800,300],textHeightMm:120,roundingMm:.1,source:'manual'};
 appendDimension(model,d);
 for(const kind of ['horizontal','vertical'] as const)appendDimension(model,{...d,id:kind,kind});
 expect(dimensionMeasurement(d)).toBeCloseTo(Math.hypot(3000.4,4000.2),8);
 expect(dimensionGeometry(d).text).toBe('5000.4');
 expect(dimensionMeasurement({...d,kind:'horizontal'})).toBeCloseTo(3000.4,8);
 expect(dimensionMeasurement({...d,kind:'vertical'})).toBeCloseTo(4000.2,8);
 expect(validateDimensions(model)).toEqual([]);
 const annotated=applyCadAnnotations(model,[{id:'text-1',text:'独立复核',x:0,y:0,coordinateSpace:'drawing-mm'}]);
 expect(validateDrawingModel(annotated).valid).toBe(true);expect(annotated.dimensions).toEqual(model.dimensions);
 const source={name:'room.pcd',bytes,units:'m' as const,synthetic:true};
 const archive=await encodeProject({source,annotations:[],settings:{},drawing:model,projection:'xy'});
 expect((await decodeProject(archive.slice().buffer as ArrayBuffer)).drawing?.dimensions).toEqual(model.dimensions);
 const data=exportCadDxf(model);const text=new TextDecoder().decode(data);
 expect((text.match(/\r\nDIMENSION\r\n/g)??[]).length).toBe(model.dimensions!.length);
 expect(text).toContain('AcDbAlignedDimension');expect(text).toContain('AcDbRotatedDimension');
 expect(text).toMatch(/72\r\n1\r\n11\r\n/);
 const {createCadSheet}=await import('../../src/cad/sheet');expect(createCadSheet(model).svg).toContain('text-anchor="middle"');
 mkdirSync('artifacts/cad-core-20261029',{recursive:true});writeFileSync('artifacts/cad-core-20261029/known-dimensions.dxf',data);writeFileSync('artifacts/cad-core-20261029/known-dimensions.json',JSON.stringify(model.dimensions,null,2));
 const corrupt=structuredClone(model);const label=corrupt.entities.find(e=>e.id===d.id+':text')!;if(label.type==='text')label.text='9999';
 expect(()=>exportCadDxf(corrupt)).toThrow('尺寸图元与定义不一致');
});
it('高度范围按源米制对全部点生效，闭区间边界可恢复，拒绝非法和颠倒范围',()=>{
 const cloud={positions:new Float32Array([0,0,-1,0,0,0,0,0,1,0,0,2,0,0,3]),visible:new Uint8Array(5)} as any;
 expect(applyClips(cloud,[{axis:'z',rangeM:[0,2],mode:'keep'}])).toBe(3);expect([...cloud.visible]).toEqual([0,1,1,1,0]);
 expect(applyClips(cloud,[])).toBe(5);
 expect(applyClips(cloud,[{axis:'z',rangeM:[0,2],mode:'remove'}])).toBe(2);
 expect(()=>validateClips([{axis:'z',rangeM:[2,0],mode:'keep'}])).toThrow();
 expect(()=>validateClips([{axis:'z',rangeM:[0,NaN],mode:'keep'}])).toThrow();
});
